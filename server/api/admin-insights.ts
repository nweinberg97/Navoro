/** Admin API: overview, analytics, audit log, organization settings, members and provider status. */
import { badRequest, conflict, forbidden, notFound, readJson, sendJson, type Router } from '../http/http.ts';
import { v } from '../lib/validate.ts';
import { hasRole, requireApp, requireRole, requireSession, type ServerContext } from './context.ts';
import { hashPassword } from '../security/crypto.ts';
import type { Tenant } from '../data/tenant.ts';
import type { OverviewResponse, ProviderStatusDTO, SettingsResponse } from '../../packages/contracts/src/admin-types.ts';

const STALE_SOURCE_DAYS = 30;

export function providerStatus(server: ServerContext): ProviderStatusDTO {
  if (server.provider) {
    return { mode: 'llm', provider: server.provider.name, model: server.provider.model, note: `Answers are generated by ${server.provider.model} from your retrieved documentation and validated before display.` };
  }
  return {
    mode: 'demo',
    provider: null,
    model: null,
    note: 'Demo mode: ANTHROPIC_API_KEY is not set, so answers are assembled directly from your retrieved documentation without a language model. Every answer is labelled accordingly.',
  };
}

function overview(server: ServerContext, t: Tenant): OverviewResponse {
  const apps = t.apps.list();
  const day = 86_400_000;
  const sources = apps.flatMap((app) => t.knowledge.list(app.id));
  const mappings = apps.flatMap((app) => t.guidance.mappings(app.id));
  const workflows = apps.flatMap((app) => t.guidance.workflows(app.id));
  const processed = sources.map((source) => source.processed_at).filter((value): value is string => Boolean(value)).sort();
  const counts = t.activity.guidanceCounts(7);
  const nextActions: OverviewResponse['nextActions'] = [];
  if (!apps.length) {
    nextActions.push({ id: 'register', title: 'Register your application', description: 'Tell Navoro where it will run and get your install snippet.', href: '/app/applications' });
  }
  for (const app of apps) {
    const appSources = sources.filter((source) => source.app_id === app.id);
    const appWorkflows = workflows.filter((workflow) => workflow.app_id === app.id);
    const envs = t.apps.environmentDTOs(app.id);
    if (!appSources.length) nextActions.push({ id: `knowledge-${app.id}`, title: `Add knowledge for ${app.name}`, description: 'Import help articles, docs URLs or the sample Lumen docs so Navoro can learn your product.', href: '/app/knowledge' });
    const failed = appSources.filter((source) => source.status === 'failed' || source.status === 'needs_attention');
    if (failed.length) nextActions.push({ id: `sources-${app.id}`, title: `${failed.length} source(s) need attention`, description: 'Review import errors and fix or remove the source.', href: '/app/knowledge' });
    const pending = appWorkflows.filter((workflow) => workflow.status === 'draft' || workflow.status === 'needs_review');
    if (pending.length) nextActions.push({ id: `review-${app.id}`, title: `Review ${pending.length} workflow(s)`, description: 'Extracted guidance stays in draft until you publish it.', href: '/app/guidance' });
    const unapproved = t.apps.catalog(app.id).filter((element) => element.approved === 0).length;
    if (unapproved) nextActions.push({ id: `metadata-${app.id}`, title: `Approve ${unapproved} discovered element(s)`, description: 'The SDK found new data-navoro-id elements. Approve them to use them as context and targets.', href: `/app/applications/${app.id}` });
    const brokenCount = mappings.filter((mapping) => mapping.app_id === app.id && mapping.validation === 'broken').length;
    if (brokenCount) nextActions.push({ id: `mappings-${app.id}`, title: `Fix ${brokenCount} broken mapping(s)`, description: 'A control referenced by guidance is no longer found in your application.', href: '/app/guidance?tab=mappings' });
    if (appWorkflows.some((workflow) => workflow.status === 'published') && !envs.some((env) => env.activeConfigVersion)) {
      nextActions.push({ id: `publish-${app.id}`, title: 'Publish a configuration', description: 'Published guidance reaches users only after you publish a configuration version.', href: `/app/applications/${app.id}` });
    }
    if (!app.last_seen_at) nextActions.push({ id: `install-${app.id}`, title: `Install the SDK in ${app.name}`, description: 'Add the script tag and open your app once to connect it.', href: `/app/applications/${app.id}` });
  }
  return {
    provider: providerStatus(server),
    applications: apps.map((app) => {
      const envs = t.apps.environmentDTOs(app.id);
      const published = envs.map((env) => env.activeConfigVersion).filter((value): value is number => value !== null);
      const age = app.last_seen_at ? Date.now() - new Date(app.last_seen_at).getTime() : null;
      return {
        id: app.id,
        name: app.name,
        connection: age === null ? 'never_connected' : age < day ? 'connected' : 'stale',
        lastSeenAt: app.last_seen_at,
        publishedVersion: published.length ? Math.max(...published) : null,
      };
    }),
    sources: {
      total: sources.length,
      ready: sources.filter((source) => source.status === 'ready').length,
      processing: sources.filter((source) => source.status === 'processing').length,
      needsAttention: sources.filter((source) => source.status === 'needs_attention').length,
      failed: sources.filter((source) => source.status === 'failed').length,
      pending: sources.filter((source) => source.status === 'pending').length,
    },
    freshness: {
      oldestProcessedAt: processed[0] ?? null,
      newestProcessedAt: processed[processed.length - 1] ?? null,
      staleCount: sources.filter((source) => !source.processed_at || Date.now() - new Date(source.processed_at).getTime() > STALE_SOURCE_DAYS * day).length,
    },
    guidance: { sessions7d: counts.sessions, answered7d: counts.answered, unresolved7d: counts.unresolved, completedWorkflows7d: counts.completed },
    mappings: {
      total: mappings.length,
      valid: mappings.filter((mapping) => mapping.validation === 'valid').length,
      unverified: mappings.filter((mapping) => mapping.validation === 'unverified').length,
      uncertain: mappings.filter((mapping) => mapping.validation === 'uncertain').length,
      broken: mappings.filter((mapping) => mapping.validation === 'broken').length,
    },
    workflows: {
      published: workflows.filter((workflow) => workflow.status === 'published').length,
      draft: workflows.filter((workflow) => workflow.status === 'draft').length,
      needsReview: workflows.filter((workflow) => workflow.status === 'needs_review').length,
    },
    recentActivity: t.activity.auditEvents(8),
    nextActions: nextActions.slice(0, 6),
  };
}

const settingsSchema = v.object({ name: v.optional(v.string({ min: 1, max: 80 })), approvalPolicy: v.optional(v.oneOf(['manual', 'auto'] as const)) });
const memberSchema = v.object({
  email: v.string({ min: 3, max: 254, pattern: /^[^\s@]+@[^\s@]+\.[^\s@]+$/, patternMessage: 'Enter a valid email address' }),
  name: v.string({ min: 1, max: 80 }),
  role: v.oneOf(['owner', 'admin', 'member'] as const),
  password: v.string({ min: 10, max: 200, trim: false }),
});
const roleSchema = v.object({ role: v.oneOf(['owner', 'admin', 'member'] as const) });

function settings(server: ServerContext, t: Tenant): SettingsResponse {
  const organization = t.activity.organization();
  if (!organization) throw notFound('Workspace not found.');
  return { organization, members: t.activity.members(), provider: providerStatus(server) };
}

export function registerInsightRoutes(router: Router, server: ServerContext): void {
  router.get('/api/admin/overview', (ctx) => {
    const { t } = requireSession(server, ctx);
    sendJson(ctx.res, 200, overview(server, t));
  });

  router.get('/api/admin/applications/:id/analytics', (ctx) => {
    const request = requireSession(server, ctx);
    const app = requireApp(request, ctx.params.id);
    const days = Math.min(90, Math.max(1, Number(ctx.url.searchParams.get('days') ?? 30) || 30));
    const policy = request.t.privacy.draft(app.id)?.policy;
    const base = request.t.activity.analytics(app.id, days, policy?.retainQuestions ?? false, policy?.analyticsEnabled ?? true);
    const staleSources = request.t.knowledge
      .list(app.id)
      .filter((source) => source.status !== 'ready' || !source.processed_at || Date.now() - new Date(source.processed_at).getTime() > STALE_SOURCE_DAYS * 86_400_000)
      .map((source) => ({ id: source.id, title: source.title, processedAt: source.processed_at, status: source.status }));
    const lowConfidenceMappings = request.t.guidance
      .mappings(app.id)
      .filter((mapping) => mapping.validation === 'broken' || mapping.validation === 'uncertain' || mapping.confidence < 0.6)
      .map((mapping) => request.t.guidance.mappingDTO(mapping));
    sendJson(ctx.res, 200, { ...base, staleSources, lowConfidenceMappings });
  });

  router.get('/api/admin/audit', (ctx) => {
    const { t } = requireSession(server, ctx);
    sendJson(ctx.res, 200, { events: t.activity.auditEvents(100) });
  });

  router.get('/api/admin/provider', (ctx) => {
    requireSession(server, ctx);
    sendJson(ctx.res, 200, providerStatus(server));
  });

  router.get('/api/admin/settings', (ctx) => {
    const { t } = requireSession(server, ctx);
    sendJson(ctx.res, 200, settings(server, t));
  });

  router.patch('/api/admin/settings', async (ctx) => {
    const request = requireSession(server, ctx);
    requireRole(request, 'admin');
    const body = await readJson(ctx, settingsSchema);
    request.t.activity.updateOrganization(body);
    request.t.activity.audit({
      actorUserId: request.session.userId,
      action: 'workspace.updated',
      targetType: 'organization',
      targetId: request.t.orgId,
      summary: body.approvalPolicy ? `Set Refresh Learning approval policy to ${body.approvalPolicy}` : `Renamed workspace to ${body.name}`,
    });
    sendJson(ctx.res, 200, settings(server, request.t));
  });

  router.post('/api/admin/members', async (ctx) => {
    const request = requireSession(server, ctx);
    requireRole(request, 'admin');
    const body = await readJson(ctx, memberSchema);
    if (body.role === 'owner' && !hasRole(request.session.role, 'owner')) throw forbidden('Only owners can add owners.');
    try {
      server.accounts.addMember(request.t.orgId, { email: body.email, name: body.name, role: body.role, passwordHash: await hashPassword(body.password) });
    } catch (error) {
      if ((error as Error).message === 'already_member') throw conflict('That person is already a member.');
      throw error;
    }
    request.t.activity.audit({ actorUserId: request.session.userId, action: 'member.added', targetType: 'user', targetId: null, summary: `Added ${body.email} as ${body.role}` });
    sendJson(ctx.res, 201, settings(server, request.t));
  });

  router.patch('/api/admin/members/:userId', async (ctx) => {
    const request = requireSession(server, ctx);
    requireRole(request, 'admin');
    const body = await readJson(ctx, roleSchema);
    const userId = ctx.params.userId ?? '';
    const current = request.t.activity.memberRole(userId);
    if (!current) throw notFound('Member not found.');
    if (userId === request.session.userId) throw badRequest('You can’t change your own role.');
    if ((current === 'owner' || body.role === 'owner') && !hasRole(request.session.role, 'owner')) throw forbidden('Only owners can grant or revoke the owner role.');
    if (current === 'owner' && body.role !== 'owner' && request.t.activity.ownerCount() <= 1) throw badRequest('A workspace needs at least one owner.');
    request.t.activity.setMemberRole(userId, body.role);
    request.t.activity.audit({ actorUserId: request.session.userId, action: 'member.role_changed', targetType: 'user', targetId: userId, summary: `Changed a member's role from ${current} to ${body.role}` });
    sendJson(ctx.res, 200, settings(server, request.t));
  });
}
